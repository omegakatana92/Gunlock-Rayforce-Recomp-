#!/usr/bin/env python3
"""embed binary/text files as C arrays: embed.py out.c [--ns rf] name=path ..."""
import sys
out = sys.argv[1]; args = sys.argv[2:]
ns = None
if args and args[0] == '--ns': ns = args[1]; args = args[2:]
lines = ['/* generated by tools/embed.py */']
if ns: lines.append('namespace %s {' % ns)
for a in args:
    name, path = a.split('=', 1)
    data = open(path, 'rb').read()
    text = path.endswith('.json')
    if text: data = data + b'\0'
    typ = 'const char' if text else 'const unsigned char'
    pre = 'extern "C" ' if (text and not ns) else ('extern ' if ns else '')
    lines.append('%s%s %s[] = {' % (pre, typ, name))
    for i in range(0, len(data), 24):
        lines.append(','.join(str(b) for b in data[i:i+24]) + ',')
    lines.append('};')
    if not text: lines.append('%sconst unsigned int %s_len = %d;' % (pre, name, len(data)))
if ns: lines.append('}')
open(out, 'w').write('\n'.join(lines) + '\n')
